"""Typed pipeline configuration and JSON (de)serialisation.

The configuration is the single source of truth for every tolerance and
threshold used by the pipeline.  Sample camera configurations are generated by
:mod:`terrain.gen_config` (never downloaded), and the stitch switch lives here
so behaviour changes without touching source code.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, fields
from pathlib import Path

from .errors import E_BAD_FRUSTUM, E_RES_TOO_HIGH, PipelineError

MAX_TILE_RESOLUTION = 2048


@dataclass(frozen=True)
class CameraConfig:
    eye: tuple[float, float, float]
    look_at: tuple[float, float, float]
    up: tuple[float, float, float]
    fov_y_deg: float
    near: float
    far: float


@dataclass(frozen=True)
class LightConfig:
    direction: tuple[float, float, float]
    ambient: float
    diffuse_albedo: float
    gamma: float


@dataclass(frozen=True)
class PipelineConfig:
    seed: int
    root_min: tuple[float, float]
    root_size: float
    max_depth: int
    tile_resolution: int
    height_scale: float
    noise_octaves: int
    camera: CameraConfig
    image_width: int
    image_height: int
    sse_threshold: float
    sse_relative_tolerance: float
    enable_stitching: bool
    light: LightConfig
    backend: str
    output_png: str
    output_contract: str

    @staticmethod
    def from_dict(data: dict) -> "PipelineConfig":
        camera = CameraConfig(**data["camera"])
        light = LightConfig(**data["light"])
        known = {f.name for f in fields(PipelineConfig)} - {"camera", "light"}
        rest = {key: value for key, value in data.items() if key in known}
        return PipelineConfig(camera=camera, light=light, **rest)

    @staticmethod
    def load(path: str | Path) -> "PipelineConfig":
        with Path(path).open("r", encoding="utf-8") as handle:
            return PipelineConfig.from_dict(json.load(handle))

    def to_dict(self) -> dict:
        return asdict(self)

    def with_overrides(self, **overrides) -> "PipelineConfig":
        data = self.to_dict()
        for key, value in overrides.items():
            if key in ("camera", "light"):
                data[key].update(value)
            else:
                data[key] = value
        return PipelineConfig.from_dict(data)

    def validate(self) -> None:
        """Validate configuration before any large allocation is attempted."""
        if not (1 <= self.tile_resolution <= MAX_TILE_RESOLUTION):
            raise PipelineError(
                E_RES_TOO_HIGH,
                f"tile_resolution={self.tile_resolution} exceeds limit "
                f"{MAX_TILE_RESOLUTION}",
            )
        if self.image_width <= 0 or self.image_height <= 0:
            raise PipelineError(
                E_RES_TOO_HIGH,
                f"image dimensions must be positive, got "
                f"{self.image_width}x{self.image_height}",
            )
        camera = self.camera
        if camera.near <= 0.0:
            raise PipelineError(
                E_BAD_FRUSTUM,
                f"near plane must be > 0, got {camera.near}",
            )
        if camera.far <= camera.near:
            raise PipelineError(
                E_BAD_FRUSTUM,
                f"far ({camera.far}) must exceed near ({camera.near})",
            )
        if camera.fov_y_deg <= 0.0 or camera.fov_y_deg >= 180.0:
            raise PipelineError(
                E_BAD_FRUSTUM,
                f"fov_y_deg must be in (0, 180), got {camera.fov_y_deg}",
            )
        eye = camera.eye
        target = camera.look_at
        if (eye[0] - target[0]) ** 2 + (eye[1] - target[1]) ** 2 + (
            eye[2] - target[2]
        ) ** 2 == 0.0:
            raise PipelineError(
                E_BAD_FRUSTUM, "eye and look_at must not coincide"
            )
        up = camera.up
        if up[0] ** 2 + up[1] ** 2 + up[2] ** 2 == 0.0:
            raise PipelineError(E_BAD_FRUSTUM, "up vector must be non-zero")
        if self.max_depth < 0:
            raise PipelineError(
                E_BAD_FRUSTUM, f"max_depth must be >= 0, got {self.max_depth}"
            )

def write_json(path: str | Path, payload: dict) -> None:
    """Write JSON with stable key ordering so output diffs are deterministic."""
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with Path(path).open("w", encoding="utf-8", newline="\n") as handle:
        json.dump(payload, handle, indent=2, sort_keys=True)
        handle.write("\n")
