"""Deterministic WAV / timeline fixtures (no external attachments).

All randomness uses a fixed numpy seed so generated bytes are reproducible.
"""

from __future__ import annotations

import json
import os

import numpy as np
import soundfile as sf

SEED = 20261116


def sine_wave(
    duration_s: float,
    frequency_hz: float,
    sample_rate: int,
    amplitude: float = 0.5,
    channels: int = 1,
) -> np.ndarray:
    """Deterministic sine tone, optionally duplicated across channels."""
    frames = int(round(duration_s * sample_rate))
    t = np.arange(frames, dtype=np.float64) / sample_rate
    wave = amplitude * np.sin(2.0 * np.pi * frequency_hz * t)
    if channels == 2:
        wave = np.stack([wave, wave * 0.8], axis=1)
    else:
        wave = wave[:, np.newaxis]
    return wave.astype(np.float32)


def silence(duration_s: float, sample_rate: int, channels: int = 1) -> np.ndarray:
    frames = int(round(duration_s * sample_rate))
    return np.zeros((frames, channels), dtype=np.float32)


def colored_noise(duration_s: float, sample_rate: int, amplitude: float = 0.2) -> np.ndarray:
    """Seeded white noise, deterministic across runs and platforms."""
    rng = np.random.default_rng(SEED)
    frames = int(round(duration_s * sample_rate))
    return (rng.standard_normal(frames) * amplitude).astype(np.float32)[:, np.newaxis]


def write_wav(path: str, data: np.ndarray, sample_rate: int, subtype: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    sf.write(path, np.ascontiguousarray(data), sample_rate, subtype=subtype, format="WAV")


def build_full_scenario(root: str) -> str:
    """Create the main acceptance scenario; returns the input directory."""
    input_dir = os.path.join(root, "input")
    os.makedirs(input_dir, exist_ok=True)

    # Different sample rates and bit depths, all internally resampled to 48k.
    write_wav(
        os.path.join(input_dir, "tone_441_16.wav"),
        sine_wave(1.0, 440.0, 44100, amplitude=0.4),
        44100,
        "PCM_16",
    )
    write_wav(
        os.path.join(input_dir, "noise_32k_24.wav"),
        colored_noise(1.0, 32000, amplitude=0.25),
        32000,
        "PCM_24",
    )
    write_wav(
        os.path.join(input_dir, "stereo_48k_32f.wav"),
        sine_wave(1.0, 880.0, 48000, amplitude=0.3, channels=2),
        48000,
        "FLOAT",
    )
    write_wav(
        os.path.join(input_dir, "short_48k.wav"),
        sine_wave(0.3, 220.0, 48000, amplitude=0.5),
        48000,
        "PCM_16",
    )
    write_wav(
        os.path.join(input_dir, "loop_tone.wav"),
        sine_wave(0.25, 660.0, 48000, amplitude=0.45),
        48000,
        "PCM_16",
    )
    write_wav(
        os.path.join(input_dir, "quiet.wav"),
        sine_wave(1.0, 330.0, 48000, amplitude=0.0008),
        48000,
        "PCM_16",
    )

    # A deliberately corrupt WAV (valid header bytes are missing entirely).
    with open(os.path.join(input_dir, "broken.wav"), "wb") as handle:
        handle.write(b"NOT-A-RIFF-FILE" * 8)

    timeline = {
        "sample_rate": 48000,
        "events": [
            {
                "start_ms": 0,
                "end_ms": 1000,
                "clip": "tone_441_16.wav",
                "fade_in_ms": 20,
                "fade_out_ms": 20,
                "gain_db": 0.0,
                "priority": 1,
                "loop": False,
            },
            {
                # Overlaps event 0; higher priority wins in [500, 900).
                "start_ms": 500,
                "end_ms": 900,
                "clip": "stereo_48k_32f.wav",
                "fade_in_ms": 10,
                "fade_out_ms": 10,
                "gain_db": -3.0,
                "priority": 5,
                "loop": False,
            },
            {
                # Equal-priority overlap with event 1 region; later index wins.
                "start_ms": 700,
                "end_ms": 1200,
                "clip": "noise_32k_24.wav",
                "fade_in_ms": 0,
                "fade_out_ms": 50,
                "gain_db": -6.0,
                "priority": 5,
                "loop": False,
            },
            {
                # Clip shorter than event, no loop -> silence padding.
                "start_ms": 1300,
                "end_ms": 2000,
                "clip": "short_48k.wav",
                "fade_in_ms": 5,
                "fade_out_ms": 5,
                "gain_db": 0.0,
                "priority": 0,
                "loop": False,
            },
            {
                # Clip shorter than event with loop -> tiled, no junction fade.
                "start_ms": 2100,
                "end_ms": 2700,
                "clip": "loop_tone.wav",
                "fade_in_ms": 10,
                "fade_out_ms": 10,
                "gain_db": 0.0,
                "priority": 2,
                "loop": True,
            },
            {
                # Corrupt clip: must be skipped while other events continue.
                "start_ms": 2800,
                "end_ms": 3000,
                "clip": "broken.wav",
                "fade_in_ms": 0,
                "fade_out_ms": 0,
                "gain_db": 0.0,
                "priority": 0,
                "loop": False,
            },
            {
                # Very quiet content to exercise the low-loudness path.
                "start_ms": 3100,
                "end_ms": 3600,
                "clip": "quiet.wav",
                "fade_in_ms": 0,
                "fade_out_ms": 0,
                "gain_db": 0.0,
                "priority": 0,
                "loop": False,
            },
        ],
    }
    with open(os.path.join(input_dir, "timeline.json"), "w", encoding="utf-8") as handle:
        json.dump(timeline, handle, indent=2)
    return input_dir


def write_timeline(root: str, events: list[dict], sample_rate: int = 48000) -> str:
    """Helper for focused tests: write a custom timeline into ``root``."""
    os.makedirs(root, exist_ok=True)
    payload = {"sample_rate": sample_rate, "events": events}
    with open(os.path.join(root, "timeline.json"), "w", encoding="utf-8") as handle:
        json.dump(payload, handle)
    return root
